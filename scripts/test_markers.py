# --- «Финальная мораль» (паттерн #59, категория N: дискурсный слой) --------
# Лексический подкласс дискурсного паттерна. StoryScope (arXiv:2604.03136v6):
# явная мораль у ИИ в 77% историй против 52% у людей. Разрыв в полтора раза,
# поэтому ложные срабатывания тут дороже пропусков: человек так пишет часто.
# Шаблоны сужены до указательных («этой/эта») и до финальной позиции для
# голых «мораль проста/такова»; негативы ниже держат каждое сужение.
ФМ = "Финальная мораль"
check(soft_hits("Мораль этой истории проста: доверяй, но проверяй.", ФМ) >= 1,
      "«мораль этой истории» ловится")
check(soft_hits("Я потерял три недели на переделку. Мораль такова: без плана не начинай.", ФМ) >= 1,
      "«мораль такова» последней фразой ловится")
check(soft_hits("Он вернул деньги и больше не звонил. Мораль проста: не связывайся с ним.", ФМ) >= 1,
      "«мораль проста» последней фразой ловится")
check(soft_hits("Эта история учит нас беречь время.", ФМ) >= 1,
      "«эта история учит нас» ловится")
check(soft_hits("Эта история о том, что упорство важнее таланта.", ФМ) >= 1,
      "«эта история о том, что» (тезис) ловится")
check(soft_hits("Мораль и право расходятся в предмете регулирования.", ФМ) == 0,
      "«мораль» как понятие этики НЕ ловится")
check(soft_hits("История учит внимательности к деталям.", ФМ) == 0,
      "«история учит» без обращения к читателю НЕ ловится")
check(soft_hits("Уроки истории в десятом классе перенесли на среду.", ФМ) == 0,
      "школьные «уроки истории» НЕ ловятся")
check(soft_hits("Эта история о том, как мы переезжали в новый офис.", ФМ) == 0,
      "«история о том, как» (события, не тезис) НЕ ловится")
# Негативы на живой человеческой прозе: до сужения регулярок ловилось всё
# перечисленное ниже. CONTRIBUTING требует проверки именно на них.
check(soft_hits("Мораль проста: не подписывай договор, который не читал. Дальше уже дело техники.", ФМ) == 0,
      "«мораль проста» в середине текста (разговорная связка) НЕ ловится")
check(soft_hits("В басне мораль проста, а исполнение так себе.", ФМ) == 0,
      "«мораль проста» внутри фразы, без границы предложения, НЕ ловится")
check(soft_hits("Мораль истории Раскольникова школьникам объясняют плохо.", ФМ) == 0,
      "литературный разбор «мораль истории X» без указательного НЕ ловится")
check(soft_hits("Какая мораль истории про лису и виноград, если лиса права?", ФМ) == 0,
      "разбор басни «мораль истории про...» НЕ ловится")
check(soft_hits("История учит нас тому, что она ничему не учит.", ФМ) == 0,
      "публицистический оборот «история учит нас» без указательного НЕ ловится")
check(soft_hits("Наш историк учит нас работать с источниками.", ФМ) == 0,
      "«историк» (а не «история») НЕ ловится: окончания перечислены явно")
check(soft_hits("Эта история напоминает нам сюжет из Гоголя.", ФМ) == 0,
      "«эта история напоминает нам» (сравнение, не мораль) НЕ ловится")

