#!/usr/bin/env python3
"""Регресс-тесты метрик. Без pytest: чистые assert, запуск `python scripts/test_markers.py`.

Фиксируют классы ошибок, которые уже случались, чтобы не вернулись:
- «данные/данных» (data) НЕ должны ловиться как канцелярит «данный» (был ложный
  бан на ML/статистических текстах);
- «данный метод» (определитель) ДОЛЖЕН ловиться;
- длинное тире считается, дефис — нет;
- AI-текст и человеческий текст уверенно разделяются по метрикам.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "skills" / "humanizer-ru" / "scripts"))

from humanizer_metrics import analyze, cleanliness_score
from humanizer_metrics.markers import GENRE_MUTED_BANS, mute_by_genre
from humanizer_metrics.markers import (effective_hard_bans, scan_hard_bans,
                                       scan_markers)

passed = 0


def check(cond: bool, msg: str) -> None:
    global passed
    assert cond, f"FAIL: {msg}"
    passed += 1


def ban_names(text: str) -> set[str]:
    return {h.marker for h in scan_hard_bans(text)}


# --- «данные» (data) не канцелярит ---------------------------------------
check("Данный/Данная/Данное" not in ban_names("Модель учится на размеченных данных."),
      "«данных» (data) не должно быть HARD BAN")
check("Данный/Данная/Данное" not in ban_names("Качество данных важнее архитектуры."),
      "«данных» (data, род.) не должно быть HARD BAN")
check("Данный/Данная/Данное" in ban_names("Данный метод хорош."),
      "«данный» (определитель) должен ловиться")
check("Данный/Данная/Данное" in ban_names("В данной ситуации это работает."),
      "«данной» (определитель) должен ловиться")

# --- тире -----------------------------------------------------------------
check("Длинное тире" in ban_names("Это длинное тире — маркер."), "длинное тире ловится")
check("Длинное тире" not in ban_names("Это дефис-маркер, всё ок."), "дефис не ловится как тире")
check(analyze("Текст — с тире.").rhythm.em_dash == 1, "em_dash считается")
check(analyze("Текст с дефисом-словом.").rhythm.em_dash == 0, "дефис не считается em_dash")

# --- базовые HARD BANS ----------------------------------------------------
check("В современном мире" in ban_names("В современном мире всё иначе."), "пустое открытие")
check("Является" in ban_names("Python является языком."), "«является» ловится")
check(len(scan_markers("осуществление реализация внедрение")) >= 1, "канцелярит-маркеры ловятся")

# --- «таким образом»: вводный вывод банится, обстоятельство образа действия нет --
# Омоним: AI-клише «Таким образом, ...» (вводный вывод) против живого «таким
# образом, что...» (= «такой манерой»). Раньше regex ловил оба → ложный бан на
# художественной прозе («говорить таким образом, что...»). Узкий regex держит AI
# и отпускает обстоятельство — проверено: все 7/7 raw остаются под баном.
ТО = "Подводя итог / Таким образом"
check(ТО in ban_names("Рынок растёт. Таким образом, выбор очевиден."),
      "«Таким образом,» как вводный вывод после точки ловится")
check(ТО in ban_names("Таким образом, мы видим результат."),
      "«Таким образом,» в начале текста ловится")
check(ТО in ban_names("И, таким образом, всё сошлось."),
      "«таким образом», обособленное запятыми, ловится")
check(ТО not in ban_names("Он говорил с каждым таким образом, что все смеялись."),
      "обстоятельство «таким образом, что» (образ действия) НЕ банится")
check(ТО not in ban_names("Поступи таким образом."),
      "«таким образом» без вводной запятой (обстоятельство) НЕ банится")
check(ТО in ban_names("Подводя итог, отметим главное."),
      "«подводя итог» остаётся под баном безусловно")
check(ТО in ban_names("Итоги\nТаким образом, проект закрыт."),
      "«Таким образом,» после заголовка без точки (перенос строки) ловится")
check(ТО in ban_names("Выводы ниже.\n- Таким образом, всё сошлось."),
      "«Таким образом,» в пункте списка ловится")

# --- «от X до Y»: банится ложный диапазон несвязанных понятий, не любой ----
# Регекс не различает семантику, поэтому исключаем заведомо легитимные классы:
# числа, имена собственные (с заглавной), повтор одного слова (идиомы).
ОТ = "от X до Y (ложный диапазон)"
check(ОТ in ban_names("Подходит всем: от стартапов до корпораций."),
      "«от стартапов до корпораций» (несвязанные понятия) банится")
check(ОТ in ban_names("Курс полезен всем: от новичков до профессионалов."),
      "«от новичков до профессионалов» банится")
check(ОТ not in ban_names("Зарплата выросла от 10 до 15 процентов."),
      "числовой диапазон «от 10 до 15» не банится")
check(ОТ not in ban_names("Поезд идёт от Москвы до Твери."),
      "имена собственные «от Москвы до Твери» не банятся")
check(ОТ not in ban_names("Работал от зари до зари."),
      "идиома с повтором «от зари до зари» не банится")

# --- частотный порог «Является» (SKILL: >1 раза на 500 слов) ---------------
from humanizer_metrics.markers import effective_hard_bans


def eff_names(text: str, words: int) -> set[str]:
    return {h.marker for h in effective_hard_bans(scan_hard_bans(text), words)}


check("Является" not in eff_names("Python является языком.", words=200),
      "одиночное «является» не хард-бан (остаётся мягким маркером)")
check("Является" in eff_names("Python является языком. Java является платформой.", words=12),
      "два «является» на коротком тексте = хард-бан (плотность выше 1/500)")
check("Является" not in eff_names("Python является языком. Java является платформой.", words=1500),
      "два «является» на 1500 слов укладываются в частоту, не бан")
check("В современном мире" in eff_names("В современном мире всё иначе.", words=5),
      "обычные хард-баны частотным порогом не смягчаются")

# --- мягкие маркеры: границы слова и конструкции --------------------------
def soft_hits(text: str, cat: str) -> int:
    return sum(h.count for h in scan_markers(text) if h.category == cat)


check(soft_hits("Python является языком.", "Кальки") >= 1,
      "«является» остаётся мягким маркером (Кальки)")
check(any(h.marker == "является" for h in scan_markers("Python является языком.")),
      "метка маркера в отчёте человекочитаема («является»), а не регекс")
check(any(h.marker == "таким образом, (вводное)"
          for h in scan_markers("Рынок вырос. Таким образом, выбор очевиден.")),
      "метка вводного «таким образом» человекочитаема")
check(soft_hits("В городе появляется новый парк.", "Кальки") == 0,
      "«появляется» не должно ловиться как «является»")
check(soft_hits("Это не ошибка, это почерк.", "Параллелизмы") >= 1,
      "конструкция «это не X, это Y» ловится")
check(soft_hits("Это не может не радовать жителей.", "Параллелизмы") == 0,
      "обычное отрицание «это не...» не маркер")
check(soft_hits("Рынок вырос. Таким образом, выбор очевиден.", "Формула-выводы") >= 1,
      "вводный «таким образом,» остаётся мягким маркером")
check(soft_hits("Он устроен таким образом, что не ломается.", "Формула-выводы") == 0,
      "обстоятельство «таким образом, что» не мягкий маркер (сужение как в хард-бане)")

# --- технические маркеры: гомоглифы и невидимые символы (SKILL.md §сканер) --
check(soft_hits("Это обычнoе слово с подменой.", "Технические маркеры") >= 1,
      "латинская буква внутри кириллического слова (гомоглиф) ловится")
check(soft_hits("Сло​во с невидимым разделителем.", "Технические маркеры") >= 1,
      "zero-width символ (U+200B) внутри слова ловится")
check(soft_hits("Сло⁠во с word joiner внутри.", "Технические маркеры") >= 1,
      "word joiner (U+2060) ловится")
check(soft_hits("Метка‎ направления в тексте.", "Технические маркеры") >= 1,
      "bidi-метка LRM (U+200E) ловится")
check(soft_hits("Текст с‮ переворотом.", "Технические маркеры") >= 1,
      "bidi override RLO (U+202E) ловится")
check(soft_hits("Эмодзи ☝️ с вариационным селектором.", "Технические маркеры") == 0,
      "вариационный селектор эмодзи (U+FE0F) не невидимый маркер")
check(soft_hits("Цена 25 000 рублей за штуку.", "Технические маркеры") == 0,
      "неразрывный пробел (U+00A0) легитимная типографика, не маркер")
check(soft_hits("Наш IT-отдел работает с web-версией продукта.", "Технические маркеры") == 0,
      "легитимная латиница (IT, web) через дефис не гомоглиф")
check(soft_hits("Чистый русский текст без подмен.", "Технические маркеры") == 0,
      "чистый текст не даёт технических маркеров")

# --- «Деепричастные-кальки» влиты в «Кальки»: движок один-в-один со SKILL.md --
check(soft_hits("Следует учитывать контекст. Необходимо отметить рост.", "Кальки") >= 2,
      "«следует учитывать» и «необходимо отметить» ловятся как Кальки")
check("Деепричастные-кальки" not in {h.category for h in scan_markers("Стоит помнить о рисках.")},
      "категории «Деепричастные-кальки» больше нет (не описана в SKILL.md)")
check(soft_hits("Стоит помнить о рисках.", "Кальки") >= 1,
      "«стоит помнить» ловится как Кальки")

# --- «Самомаркировка честности» (паттерн #54, приоритет A) -----------------
# Позитивы: фразы из каталога (сканер, строка «Самомаркировка честности»).
