# --- жанровый фильтр (замер на AINL-Eval, см. eval/ainl_calibration.py) ----
from humanizer_metrics.markers import (GENRE_MUTED_BANS, GENRE_MUTED_CATEGORIES,
                                       mute_by_genre)
from humanizer_metrics.score import cleanliness_score

ACAD = ("Данное исследование является актуальным. В условиях цифровизации "
        "подход подчёркивает важность анализа — результаты представлены ниже. "
        "Таким образом, реализация внедрения осуществляется в рамках проекта.")
acad_rep = analyze(ACAD)
strict = effective_hard_bans(acad_rep.hard_bans, acad_rep.rhythm.words)
muted = mute_by_genre(strict, "academic", GENRE_MUTED_BANS)
check(len(strict) > len(muted), "жанр academic снимает часть банов")
check(not muted, f"в академическом регистре банов не остаётся: {[h.marker for h in muted]}")
check(mute_by_genre(strict, None, GENRE_MUTED_BANS) == strict,
    "без жанра фильтр не срабатывает (умолчание строгое)")
check(mute_by_genre(strict, "marketing", GENRE_MUTED_BANS) == strict,
    "жанр marketing ничего не снимает")

soft_strict = acad_rep.markers
soft_acad = mute_by_genre(soft_strict, "academic", GENRE_MUTED_CATEGORIES)
check(len(soft_acad) < len(soft_strict), "жанр academic снимает канцелярит и кальки")
check(any(h.category == "Неодушевлённый субъект" for h in soft_acad),
    "разделяющий маркер #55 в академическом жанре остаётся (AI/чел 4.4x на AINL-Eval)")
check(cleanliness_score(acad_rep, "academic").score > cleanliness_score(acad_rep).score,
    "score в академическом жанре выше строгого")
check("Длинное тире" in GENRE_MUTED_BANS["fiction"],
    "в художественном жанре длинное тире не бан")

# Формула «открывает новые X»: вариант с «возможностями» найден шахтой
# (eval/mine_patterns.py) как самый частый и до v3.16 проходил мимо бана.
for phrase in ("открывает новые возможности", "открывают новые возможности",
               "открывает новые горизонты", "открывает новые перспективы"):
    check(any(h.marker.startswith("Открывает новые") for h in scan_hard_bans(phrase)),
          f"бан ловит «{phrase}»")
check(not scan_hard_bans("открывает окно в новые комнаты"),
      "бан не цепляет случайное соседство слов")

# Маркеры, добытые шахтой из AINL-Eval и проверенные на людях перед добавлением.
for phrase, cat in (("Особое внимание уделяется роли фермента.", "Канцелярит"),
                    ("Внимание уделено анализу выборки.", "Канцелярит"),
                    ("Работа посвящена разработке метода.", "Канцелярит"),
                    ("Исследование фокусируется на свойствах сплава.", "Кальки")):
    check(cat in {h.category for h in scan_markers(phrase)},
          f"сканер ловит «{phrase[:28]}…» как {cat}")
check(not scan_markers("Он посвящён семье и не фокусирует взгляд."),
      "узкие формы не цепляют бытовую речь")

# --- разделение AI vs человек по метрикам --------------------------------
ai = analyze("В современном мире технология является инструментом. "
             "Стоит отметить, что данный подход открывает новые горизонты.")
human = analyze("Я попробовал три раза. Не вышло. Потом понял, в чём дело: забыл про кэш.")
check(ai.hard_ban_count > human.hard_ban_count, "у AI больше HARD BANS, чем у человека")
check(human.rhythm.cv_len > ai.rhythm.cv_len, "у человека ритм рванее (CV выше)")

# --- тире: оба знака остаются банами ---------------------------------------
# Класс ошибки: доля документов в НЕсопряжённых корпусах говорит, что тире это
# признак человека (M4: 42.3% против 3.3%), и по ней бан однажды сняли. Парный
# замер на одних и тех же постах говорит обратное: Qwen3-4B добавил длинное тире
# в 45 текстов из 45, где его не было, qwen2.5 в 19 из 31, Opus 5 в 4 из 15.
# Семейство gemma подменяет длинное коротким: человек 6% против 80%.
DASH_TEXT = "Я попробовал три раза — не вышло. Потом понял, в чём дело: забыл про кэш."
dash = analyze(DASH_TEXT)
check("Длинное тире" in {h.marker for h in
                         effective_hard_bans(dash.hard_bans, dash.rhythm.words)},
      "длинное тире остаётся штрафуемым баном")
check("Короткое тире" in {h.marker for h in scan_hard_bans("Он сказал – и ушёл.")},
      "короткое тире ловится отдельным баном")
check("Короткое тире" not in {h.marker for h in scan_hard_bans("Диапазон 10–15 штук.")},
      "числовой диапазон 10–15 короткое тире не считает")
check("Длинное тире" not in {h.marker for h in
                             mute_by_genre(scan_hard_bans(DASH_TEXT), "academic",
                                           GENRE_MUTED_BANS)},
      "в академическом жанре тире по-прежнему снимается")

# --- цель метрики: ноль это не середина человеческого распределения --------
long_clean = analyze(" ".join(
    ["Вчера пошёл в гараж, а там мышь.", "Сидит, смотрит.", "Я ей: ты чего тут забыла.",
     "Молчит, конечно.", "Насыпал хлеба, ушёл.", "Утром хлеба нет, зато лежит гайка.",
     "Не моя гайка.", "У меня таких вообще нет.", "Жена говорит, что я выдумал.",
     "Но гайка лежит до сих пор.", "Показывал соседу, он сказал, что это к деньгам.",
     "Денег пока не было.", "Гайка есть.", "Теперь каждое утро проверяю верстак.",
     "Мало ли.", "Вдруг принесёт что поинтереснее."] * 4))
sc = cleanliness_score(long_clean)
check(sc.score >= 85, "чистый длинный текст остаётся в полосе «чисто»")
check(any("стерильно" in n for n in sc.notes),
      "при нуле банов и маркеров отдаётся заметка о стерильности")
check(not any("стерильно" in n for n in cleanliness_score(ai).notes),
      "текст с маркерами заметку о стерильности не получает")


# --- код и короткие цитаты не текст автора ---------------------------------
from humanizer_metrics import mask_code_and_quotes  # noqa: E402

quoted = "Статья о клише: фраза «В современном мире» открывает половину лендингов."
check(analyze(quoted).hard_ban_count == 0,
      "бан внутри короткой цитаты в ёлочках не считается")
long_quote = ("Он сказал: «В современном мире каждый человек стоит перед выбором, "
              "и данный выбор определяет всю его дальнейшую жизнь и карьеру»")
check(analyze(long_quote).hard_ban_count >= 1,
      "длинная цитата (прямая речь) остаётся под сканером")
fenced = "Текст.\n```\n# В современном мире данный код является примером\n```\nКонец."
check(analyze(fenced).hard_ban_count == 0, "баны внутри блока кода не считаются")
inline = "Переменная `data_is_valid` не является маркером."
check(analyze(inline).hard_ban_count == analyze("Переменная  не является маркером.").hard_ban_count,
      "инлайн-код вырезан, проза вокруг сканируется как прежде")
masked = mask_code_and_quotes("а «б»\nв `г`")
check(len(masked) == len("а «б»\nв `г`") and masked.count("\n") == 1,
      "маска сохраняет длину и переводы строк")
check(analyze("От «В современном мире» до «Стоит отметить, что» один шаг.").hard_ban_count == 0,
      "две цитаты подряд не склеиваются в новый бан")
check(analyze("Стоит отметить, что цитаты тут нет.").hard_ban_count == 1,
      "бан вне цитаты считается как раньше")
fence_in_code = '```\nx = "```"\n```\n\nВ современном мире всё сложно.\n\n```\ncode\n```\n'
check(analyze(fence_in_code).hard_ban_count == 1,
      "три кавычки внутри строки кода не сдвигают границу блока: проза между блоками сканируется")
check(analyze("```\nВ современном мире\n```").hard_ban_count == 0, "ограда в начале строки закрывает блок")
blockquote = "Разбираю пример:\n\n> В современном мире данная технология играет ключевую роль.\n\nВидите штампы?"
check(analyze(blockquote).hard_ban_count == 0, "markdown-цитата через > не текст автора")
check(analyze("> цитата\n\nСтоит отметить, что дальше проза.").hard_ban_count == 1,
      "проза после markdown-цитаты сканируется")
dash_quote = "Он назвал книгу «Война — и мир» и ушёл домой. " * 3
check(analyze(dash_quote).rhythm.em_dash == 0, "тире внутри короткой цитаты не считается типографикой автора")
check(analyze("Он ушёл — и не вернулся.").rhythm.em_dash == 1, "тире в прозе автора считается")


