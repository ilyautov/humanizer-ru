#!/usr/bin/env python3
"""Согласование существительного с числительным. Общий модуль двух гейтов.

Зачем отдельный файл: счётчики протаскивает по витрине bump_release.py, а он
подставляет только цифру. Существительное рядом остаётся от прошлого числа, и
карточка плагина уезжает в магазин с «64 паттернов» вместо «64 паттерна» —
ровно тот же класс бага, что «12 категорий» при тринадцати, только заметить
его в дифе труднее: цифра-то верная.

Здесь два уровня. plural() — школьное правило (11-14 особые, потом по
последней цифре). agreement_drift()/fix_agreement() — применение правила к
живому тексту, и вот тут осторожность: числительное управляет
существительным только в именительном и винительном. После предлога падеж
задаёт предлог, и трогать слово нельзя: «каталог из 64 признаков» и
«проходит по всем 64 пунктам» верны при любом счётчике. Поэтому правится
только счётная позиция (перед числом нет управляющего слова) и только
известные леммы: подставлять окончания вслепую хуже, чем не подставлять.
"""

from __future__ import annotations

import re

__all__ = ["plural", "agreement_drift", "fix_agreement"]


def plural(n: int, one: str, few: str, many: str) -> str:
    """Русское согласование числительного: 51 признак, 64 признака, 58 признаков."""
    if n % 100 in range(11, 15):
        return many
    if n % 10 == 1:
        return one
    if n % 10 in (2, 3, 4):
        return few
    return many


# Счётные формы (им./вин. после числительного) тех существительных, которыми
# витрина считает содержимое каталога. Всё остальное не трогается: у «жёстких
# банов» число согласуется с прилагательным, у английских patterns/categories
# правило другое, у «3 режима» счётчик не наш.
COUNT_FORMS: dict[str, tuple[str, str, str]] = {
    "паттерн": ("паттерн", "паттерна", "паттернов"),
    "признак": ("признак", "признака", "признаков"),
    "пункт": ("пункт", "пункта", "пунктов"),
    "маркер": ("маркер", "маркера", "маркеров"),
    "категория": ("категория", "категории", "категорий"),
    "запрет": ("запрет", "запрета", "запретов"),
    "бан": ("бан", "бана", "банов"),
}

_FORM_TO_LEMMA = {form: lemma for lemma, forms in COUNT_FORMS.items() for form in forms}

# Слова, после которых падеж задаёт не числительное: предлоги и согласованные
# с ними местоимения. «из 64 признаков», «по всем 64 пунктам», «в 14
# категориях» — верны как есть, правило счётной позиции к ним не применяется.
GOVERNORS = {
    "из", "от", "до", "для", "около", "свыше", "более", "менее", "против",
    "по", "с", "со", "в", "во", "на", "о", "об", "обо", "при", "к", "ко",
    "над", "под", "за", "между", "среди", "чем",
    "всем", "всеми", "всех", "этим", "этими", "этих", "тем", "теми", "тех",
}

_RE_NUM_NOUN = re.compile(r"\b(\d+)(\s+)([а-яё]+)", re.IGNORECASE)


def _prev_token(text: str, pos: int) -> str:
    head = text[:pos].rstrip()
    if not head:
        return ""
    return re.sub(r"\W+", "", head.split()[-1], flags=re.UNICODE).lower()


def agreement_drift(text: str) -> list[tuple[int, str, str]]:
    """Рассогласования «число + существительное» в счётной позиции.

    Возвращает [(позиция, что стоит, что должно стоять)].
    """
    out: list[tuple[int, str, str]] = []
    for m in _RE_NUM_NOUN.finditer(text):
        noun = m.group(3)
        lemma = _FORM_TO_LEMMA.get(noun.lower())
        if lemma is None:
            continue
        if _prev_token(text, m.start()) in GOVERNORS:
            continue
        want = plural(int(m.group(1)), *COUNT_FORMS[lemma])
        if want != noun.lower():
            out.append((m.start(), f"{m.group(1)} {noun}", f"{m.group(1)} {want}"))
    return out


def fix_agreement(text: str) -> str:
    """Ставит существительное в счётной позиции в форму по числу рядом."""
    def repl(m: re.Match[str]) -> str:
        noun = m.group(3)
        lemma = _FORM_TO_LEMMA.get(noun.lower())
        if lemma is None or _prev_token(text, m.start()) in GOVERNORS:
            return m.group(0)
        return m.group(1) + m.group(2) + plural(int(m.group(1)), *COUNT_FORMS[lemma])

    return _RE_NUM_NOUN.sub(repl, text)
